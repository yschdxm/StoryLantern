#!/usr/bin/env node
/**
 * 补齐 `gen/android` 里那两个 **Tauri CLI 生成的**文件。
 *
 * 为什么需要：为了自己控制**签名与渠道**（以及可比对的构建），`scripts/build-android.mjs` 绕过
 * `tauri android build` **直接调 gradle**。但 `settings.gradle` 第 3 行就 `apply from: 'tauri.settings.gradle'`，
 * 那个文件是 CLI 生成的 —— 干净机器上没有它，Gradle 直接失败：
 *   `Could not read script '.../gen/android/tauri.settings.gradle' as it does not exist.`
 * 这正是**第一次真 runner 运行**抓到的（本机能跑，是因为我的 `gen/` 里恰好留着上次 CLI 构建的产物）。
 *
 * 文件内容指向**本机 cargo registry 里的 tauri crate**（绝对路径），所以每台机器必须自己算，
 * 不能把某台机器的路径提交进去（本机用的是 aliyun 镜像，CI 用的是 crates.io，路径完全不同）。
 *
 * 用法：node scripts/android-tauri-settings.mjs
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const GEN = path.join(ROOT, 'apps', 'shell', 'src-tauri', 'gen', 'android');
const SETTINGS = path.join(GEN, 'tauri.settings.gradle');
const PROPS = path.join(GEN, 'app', 'tauri.properties');
const LOCK = path.join(ROOT, 'apps', 'shell', 'src-tauri', 'Cargo.lock');
const CONF = path.join(ROOT, 'apps', 'shell', 'src-tauri', 'tauri.conf.json');

function fail(message) {
  console.error(`  ✗ ${message}`);
  process.exit(1);
}

if (!existsSync(GEN)) fail(`找不到 ${path.relative(ROOT, GEN)}：先跑一次 tauri android init（见 docs/PACKAGING.md）`);

/** 从 Cargo.lock 读 tauri 的版本（不解析整个 lock，只找那一段）。 */
function tauriVersion() {
  if (!existsSync(LOCK)) return undefined;
  const text = readFileSync(LOCK, 'utf8');
  const match = /\[\[package\]\]\s+name = "tauri"\s+version = "([^"]+)"/.exec(text);
  return match?.[1];
}

/** 在 cargo registry 里找 tauri crate 的 mobile/android 目录。 */
function findTauriAndroidDir(version) {
  const cargoHome = process.env.CARGO_HOME ?? path.join(homedir(), '.cargo');
  const srcRoot = path.join(cargoHome, 'registry', 'src');
  if (!existsSync(srcRoot)) return undefined;
  const wanted = `tauri-${version}`;
  for (const registry of readdirSync(srcRoot)) {
    const candidate = path.join(srcRoot, registry, wanted, 'mobile', 'android');
    if (existsSync(candidate)) return candidate;
  }
  return undefined;
}

// ---- 1) tauri.settings.gradle ----
const version = tauriVersion();
const androidDir = version === undefined ? undefined : findTauriAndroidDir(version);

if (androidDir === undefined) {
  if (existsSync(SETTINGS)) {
    console.log(`  ✓ tauri.settings.gradle 已存在（本机 cargo registry 里找不到 tauri-${version ?? '?'}，保持原样）`);
  } else {
    fail(
      `找不到 tauri crate 的 mobile/android 目录，也找不到 ${path.relative(ROOT, SETTINGS)}。\n` +
        '    先跑一次 `pnpm exec tauri android init --ci`（或 `cargo fetch` 把 tauri 拉下来）再试。',
    );
  }
} else {
  // Java 字符串里反斜杠要转义；非 Windows 用正斜杠即可。
  const literal = androidDir.replace(/\\/g, '\\\\');
  const content = [
    '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
    "include ':tauri-android'",
    `project(':tauri-android').projectDir = new File("${literal}")`,
    '',
  ].join('\n');
  const previous = existsSync(SETTINGS) ? readFileSync(SETTINGS, 'utf8') : '';
  if (previous === content) {
    console.log(`  ✓ tauri.settings.gradle 已正确（指向 ${androidDir}）`);
  } else {
    writeFileSync(SETTINGS, content, 'utf8');
    console.log(`  ✓ tauri.settings.gradle ${previous === '' ? '已生成' : '已更正'} → ${androidDir}`);
  }
}

// ---- 2) app/tauri.properties（versionName / versionCode 的来源）----
if (!existsSync(PROPS)) {
  const version_ = String(JSON.parse(readFileSync(CONF, 'utf8')).version ?? '1.0');
  writeFileSync(
    PROPS,
    [
      '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
      `tauri.android.versionName=${version_}`,
      'tauri.android.versionCode=1',
      '',
    ].join('\n'),
    'utf8',
  );
  console.log(`  ✓ app/tauri.properties 已生成（versionName=${version_}）`);
} else {
  console.log('  ✓ app/tauri.properties 已存在（渠道脚本会按渠道改写 versionName/versionCode）');
}
